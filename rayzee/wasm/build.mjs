// Builds rayzee/wasm/bvh (Rust → wasm32) and writes it into rayzee/src/bvh/BVHCoreWasm.js as base64,
// so every bundler, worker and Node host gets it with no loader of its own. `npm run build:wasm`.
// The header names a hash of the crate's sources; tests/unit/bvh/bvhCoreWasm.test.js fails when they move on without it.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const CRATE = fileURLToPath( new URL( './bvh/', import.meta.url ) );

/** Every file of the crate that changes what it builds, hashed. */
export function crateSourceHash( crate = CRATE ) {

	const files = [ 'Cargo.toml', 'Cargo.lock', '.cargo/config.toml', ...readdirSync( join( crate, 'src' ) ).sort().map( ( f ) => `src/${f}` ) ];
	const hash = createHash( 'sha256' );
	for ( const f of files ) hash.update( `${f}\0${readFileSync( join( crate, f ), 'utf8' ).replace( /\r\n/g, '\n' )}\0` );
	return hash.digest( 'hex' ).slice( 0, 16 );

}

if ( process.argv[ 1 ] && import.meta.url === pathToFileURL( process.argv[ 1 ] ).href ) {

	execFileSync( 'cargo', [ 'build', '--release' ], { cwd: CRATE, stdio: 'inherit' } );
	const wasm = readFileSync( `${CRATE}target/wasm32-unknown-unknown/release/rayzee_bvh_core.wasm` );
	const out = fileURLToPath( new URL( '../src/bvh/BVHCoreWasm.js', import.meta.url ) );
	writeFileSync( out, `// Generated by \`npm run build:wasm\` from rayzee/wasm/bvh (source ${crateSourceHash()}, ${wasm.length} B of wasm32). Do not edit.\nexport const BVH_CORE_WASM = '${wasm.toString( 'base64' )}';\n` );
	console.log( `${out}: ${wasm.length} B` );

}
